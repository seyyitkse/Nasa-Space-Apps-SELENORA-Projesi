import fs from 'node:fs'
const buf = fs.readFileSync(process.argv[2])
const jsonLen = buf.readUInt32LE(12)
const json = JSON.parse(buf.subarray(20, 20 + jsonLen).toString('utf8'))
const strip = (o) => JSON.stringify(o, (k, v) => (k === 'extras' ? undefined : v))
console.log('asset', strip(json.asset))
console.log('extensionsUsed', json.extensionsUsed, 'required', json.extensionsRequired)
console.log('scenes', strip(json.scenes))
console.log('nodes', strip(json.nodes))
console.log('meshes', strip(json.meshes))
console.log('materials', strip(json.materials))
console.log('textures', strip(json.textures), 'samplers', strip(json.samplers))
console.log('images', strip(json.images))
json.accessors.forEach((a, i) => console.log('acc', i, a.type, a.componentType, a.count, 'min', a.min, 'max', a.max, 'bv', a.bufferView, a.normalized ?? ''))
console.log('bufferViews', json.bufferViews.length, 'buffers', strip(json.buffers))
